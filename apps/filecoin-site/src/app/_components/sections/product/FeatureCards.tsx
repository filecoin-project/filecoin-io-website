import {
  CARD_ART,
  type CardArtName,
} from '@/components/sections/product/card-art'
import SectionIntro from '@/components/sections/product/SectionIntro'
import PillLink, { PillLabel } from '@/components/ui/PillLink'
import Reveal from '@/components/ui/Reveal'

export type FeatureCard = {
  art: CardArtName
  title: string
  body: string
  /** A "Learn More" pill (`href: null` until the page exists), or a "Coming soon" label. */
  link?: { label: string; href: string | null } | { label: string; soon: true }
}

/**
 * Three frosted cards, each an illustration over a title, a line of copy and an optional pill.
 * Each illustration assembles as its card scrolls in, then keeps a quiet loop going (keyframes
 * under `.ia` in globals.css; the art is generated by scripts/illustrations/build_cards.py). Three
 * across from `lg`, with the pills lined up along the bottom; between `sm` and `lg` each card
 * lays its art beside the text, and on phones it stacks.
 */
export default function FeatureCards({
  id,
  title,
  body,
  cards,
}: {
  id: string
  title: string
  body?: string
  cards: FeatureCard[]
}) {
  return (
    <section aria-labelledby={id} className="bg-paper py-section">
      <div className="container-site">
        <SectionIntro id={id} title={title} body={body} />
        <ul className="mt-[clamp(2rem,1.648rem+1.502vw,3rem)] grid grid-cols-1 gap-[clamp(1rem,0.472rem+2.254vw,2.5rem)] lg:grid-cols-3">
          {cards.map((card, i) => {
            const Art = CARD_ART[card.art]
            return (
              <Reveal key={card.title} as="li" delay={i * 90} amount={0.3}>
                <article className="grid h-full grid-cols-1 overflow-hidden rounded-3xl bg-white/40 p-[clamp(1rem,0.824rem+0.751vw,1.5rem)] shadow-[0_2px_8px_rgb(0_0_0/0.12)] sm:max-lg:grid-cols-[minmax(0,0.85fr)_minmax(0,1fr)] sm:max-lg:items-center sm:max-lg:gap-x-[clamp(1.5rem,0.5rem+3vw,2.5rem)] lg:grid-rows-[auto_1fr]">
                  <div className="ia">
                    <Art className="block h-auto w-full" />
                  </div>
                  <div className="mt-[clamp(1rem,0.824rem+0.751vw,1.5rem)] flex flex-col sm:max-lg:mt-0">
                    <h3 className="font-heading text-h4 font-book text-ink leading-[1.15] tracking-[-0.02em]">
                      {card.title}
                    </h3>
                    <p className="text-body text-ink/64 mt-2 leading-[1.15] tracking-[-0.02em] text-pretty">
                      {card.body}
                    </p>
                    {card.link && (
                      <div className="mt-auto pt-6">
                        {'soon' in card.link ? (
                          <PillLabel>{card.link.label}</PillLabel>
                        ) : (
                          <PillLink
                            href={card.link.href}
                            context={`about ${card.title}`}
                          >
                            {card.link.label}
                          </PillLink>
                        )}
                      </div>
                    )}
                  </div>
                </article>
              </Reveal>
            )
          })}
        </ul>
      </div>
    </section>
  )
}
